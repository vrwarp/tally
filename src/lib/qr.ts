/**
 * A QR code, encoded here rather than fetched.
 *
 * The one place Tally needs one is the invite QR a core member holds up to the
 * volunteer standing beside them (see `docs/team-access.md`, P2). That is a
 * ten-second act on a screen that already has the token in memory, and every
 * way of not writing this was worse: a CDN script is refused by the content
 * security policy and would put the invitation URL — a single-use grant to a
 * roster of minors — through somebody else's server; a rendering API is the
 * same leak with a round trip; and a dependency is ~15KB carried by every
 * person who never presses QR. This is ~6KB, behind `await import()`, and the
 * bytes only ever load on the press.
 *
 * Deliberately narrow. Byte mode only, error correction level M, versions 1
 * through 10 — 213 bytes, which is four times the longest join URL a
 * deployment can produce. Anything outside that throws rather than guessing,
 * because a QR that encodes the wrong thing is indistinguishable from one that
 * encodes the right thing until somebody points a phone at it.
 *
 * Every step below is ISO/IEC 18004 as it is normally implemented. The reason
 * to trust it is not the comments: `qr.test.ts` compares whole matrices
 * against fixtures generated by an unrelated encoder, so a table typed one
 * digit out fails the suite rather than shipping a square that will not scan.
 */

/**
 * The largest version this encodes, and why it stops there.
 *
 * A join URL is an origin plus `/join/` plus a 22-character token — 60-odd
 * bytes on a real deployment, which is a version 4 or 5 symbol. Version 10
 * holds 213 bytes at level M, so the ceiling is generous; going further would
 * mean carrying the whole 40-version block table for a case nobody has, and a
 * bigger symbol is a *worse* QR in the room anyway — the same phone camera has
 * to resolve more modules across the same screen.
 */
const MAX_VERSION = 10;

/**
 * How many data codewords each version holds, and how they are grouped.
 *
 * One row per version, level M only. `blocks` is the pairs the spec's table
 * gives — `[how many blocks, data codewords in each]` — because from version 8
 * up a symbol is split into two groups whose blocks differ by exactly one
 * codeword, and the interleave below has to know which is which.
 */
interface VersionSpec {
  /** Error-correction codewords per block. Every block in a version has the same count. */
  ecPerBlock: number;
  blocks: readonly (readonly [blocks: number, dataCodewords: number])[];
}

const VERSIONS: Readonly<Record<number, VersionSpec>> = {
  1: { ecPerBlock: 10, blocks: [[1, 16]] },
  2: { ecPerBlock: 16, blocks: [[1, 28]] },
  3: { ecPerBlock: 26, blocks: [[1, 44]] },
  4: { ecPerBlock: 18, blocks: [[2, 32]] },
  5: { ecPerBlock: 24, blocks: [[2, 43]] },
  6: { ecPerBlock: 16, blocks: [[4, 27]] },
  7: { ecPerBlock: 18, blocks: [[4, 31]] },
  8: { ecPerBlock: 22, blocks: [[2, 38], [2, 39]] },
  9: { ecPerBlock: 22, blocks: [[3, 36], [2, 37]] },
  10: { ecPerBlock: 26, blocks: [[4, 43], [1, 44]] },
};

/**
 * Where the alignment patterns sit, as coordinates on both axes.
 *
 * Every pair of these is a pattern centre, minus the three corners the finders
 * already occupy. Version 1 has none, which is why the table starts at 2.
 */
const ALIGNMENT_CENTRES: Readonly<Record<number, readonly number[]>> = {
  1: [],
  2: [6, 18],
  3: [6, 22],
  4: [6, 26],
  5: [6, 30],
  6: [6, 34],
  7: [6, 22, 38],
  8: [6, 24, 42],
  9: [6, 26, 46],
  10: [6, 28, 50],
};

/** Level M's two bits in the format information. L is 1, M is 0, Q is 3, H is 2. */
const EC_LEVEL_M = 0;

/** Byte mode. The other three modes are not encoded here. */
const MODE_BYTE = 0b0100;

/* -------------------------------------------------------------------------- */
/* GF(256) — the arithmetic Reed-Solomon is done in                            */
/* -------------------------------------------------------------------------- */

/*
 * Multiplication in the field is addition of logarithms, so the two tables
 * below turn every product into a lookup. `EXP` is doubled in length so the
 * sum of two logarithms never has to be reduced modulo 255 at the call site.
 * The polynomial is 0x11D, which is the one the QR spec names.
 */
const EXP = new Uint8Array(512);
const LOG = new Uint8Array(256);

for (let i = 0, x = 1; i < 255; i += 1) {
  EXP[i] = x;
  LOG[x] = i;
  x <<= 1;
  if (x & 0x100) x ^= 0x11d;
}
for (let i = 255; i < 512; i += 1) EXP[i] = EXP[i - 255]!;

function multiply(a: number, b: number): number {
  // Zero has no logarithm, and it is the one case the tables cannot answer.
  if (a === 0 || b === 0) return 0;
  return EXP[LOG[a]! + LOG[b]!]!;
}

/**
 * The generator polynomial for `degree` error-correction codewords.
 *
 * (x - α⁰)(x - α¹)…, built up one root at a time. Coefficients run
 * highest-degree first, so `poly[0]` is always 1.
 */
function generatorPoly(degree: number): Uint8Array {
  let poly = new Uint8Array([1]);
  for (let root = 0; root < degree; root += 1) {
    const next = new Uint8Array(poly.length + 1);
    for (let i = 0; i < poly.length; i += 1) {
      next[i]! ^= poly[i]!;
      next[i + 1]! ^= multiply(poly[i]!, EXP[root]!);
    }
    poly = next;
  }
  return poly;
}

/** The remainder of the data block divided by the generator: its EC codewords. */
function errorCorrection(data: Uint8Array, count: number): Uint8Array {
  const generator = generatorPoly(count);
  const remainder = new Uint8Array(count);
  for (const byte of data) {
    const factor = byte ^ remainder[0]!;
    remainder.copyWithin(0, 1);
    remainder[count - 1] = 0;
    for (let i = 0; i < count; i += 1) {
      remainder[i]! ^= multiply(generator[i + 1]!, factor);
    }
  }
  return remainder;
}

