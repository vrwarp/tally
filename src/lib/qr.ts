/* The bitstream                                                               */
/* -------------------------------------------------------------------------- */

/** Total data codewords a version holds, across every block. */
function dataCodewords(version: number): number {
  return VERSIONS[version]!.blocks.reduce((total, [count, size]) => total + count * size, 0);
}

/**
 * How many bits the character count takes.
 *
 * Byte mode uses 8 bits up to version 9 and 16 from version 10 — the one place
 * where the header length depends on a version that has not been chosen yet,
 * which is why `pickVersion` below tries each version rather than dividing.
 */
function countBits(version: number): number {
  return version < 10 ? 8 : 16;
}

/** The smallest version that fits `length` bytes, or null if none does. */
function pickVersion(length: number): number | null {
  for (let version = 1; version <= MAX_VERSION; version += 1) {
    const capacity = dataCodewords(version) * 8 - 4 - countBits(version);
    if (length * 8 <= capacity) return version;
  }
  return null;
}

/**
 * Mode, length, the bytes themselves, and whatever padding the version needs.
 *
 * The two pad bytes alternate 0xEC / 0x11 as the spec requires. They are not
 * arbitrary: a run of zeroes would give the masking stage a large flat region
 * to score, and the alternating pair is what keeps an under-filled symbol
 * looking like data.
 */
function buildData(bytes: Uint8Array, version: number): Uint8Array {
  const total = dataCodewords(version);
  const out = new Uint8Array(total);
  let bit = 0;

  const write = (value: number, width: number) => {
    for (let i = width - 1; i >= 0; i -= 1) {
      if ((value >>> i) & 1) out[bit >>> 3]! |= 0x80 >>> (bit & 7);
      bit += 1;
    }
  };

  write(MODE_BYTE, 4);
  write(bytes.length, countBits(version));
  for (const byte of bytes) write(byte, 8);

  // The terminator is up to four zero bits, and short when the symbol is
  // nearly full — writing four into a symbol with two left is what the
  // "as many as will fit" clause exists to prevent.
  write(0, Math.min(4, total * 8 - bit));
  // Then to the byte boundary, so the pad bytes start where a codeword does.
  if (bit % 8 !== 0) write(0, 8 - (bit % 8));

  for (let i = bit >>> 3, pad = 0; i < total; i += 1, pad += 1) {
    out[i] = pad % 2 === 0 ? 0xec : 0x11;
  }
  return out;
}

/**
 * The final codeword sequence: data blocks interleaved, then EC blocks.
 *
 * Interleaving is what makes the symbol survive a thumb over one corner — a
 * contiguous smudge damages a few codewords of every block rather than every
 * codeword of one, and each block can then be repaired independently.
 */
function interleave(data: Uint8Array, version: number): Uint8Array {
  const spec = VERSIONS[version]!;
  const blocks: { data: Uint8Array; ec: Uint8Array }[] = [];

  let offset = 0;
  for (const [count, size] of spec.blocks) {
    for (let i = 0; i < count; i += 1) {
      const slice = data.subarray(offset, offset + size);
      offset += size;
      blocks.push({ data: slice, ec: errorCorrection(slice, spec.ecPerBlock) });
    }
  }

  const out: number[] = [];
  const longest = Math.max(...blocks.map((block) => block.data.length));
  for (let i = 0; i < longest; i += 1) {
    for (const block of blocks) if (i < block.data.length) out.push(block.data[i]!);
  }
  for (let i = 0; i < spec.ecPerBlock; i += 1) {
    for (const block of blocks) out.push(block.ec[i]!);
  }
  return new Uint8Array(out);
}

