export interface QrCode {
  /** Modules a side. A version 4 symbol is 33. */
  size: number;
  /** The version chosen for the payload, 1 to 10. */
  version: number;
  /** Row-major and square: `modules[row][col]` is true where the square is dark. */
  modules: boolean[][];
}

/**
 * Encodes `text` as a QR symbol at error-correction level M.
 *
 * Level M rather than L because the thing being scanned is a phone screen held
 * at arm's length in a church foyer — glare and a fingerprint are the normal
 * case, and M's 15% recovery is what absorbs them. Not Q or H, which would
 * push the same URL into a denser symbol for the same camera.
 *
 * Throws for a payload no supported version holds. The caller is expected to
 * catch it and fall back to the link, which is the half of the journey that
 * always works.
 */
export function encodeQr(text: string): QrCode {
  const bytes = new TextEncoder().encode(text);
  const version = pickVersion(bytes.length);
  if (version === null) {
    throw new Error(`Too long for a QR code: ${bytes.length} bytes.`);
  }

  const symbol = blank(version);
  drawFunctionPatterns(symbol, version);
  drawCodewords(symbol, interleave(buildData(bytes, version), version));

  /*
   * Every mask is drawn, scored and undone, and the best-scoring one is drawn
   * again. Eight passes over a 33×33 grid is nothing next to the network round
   * trip that produced the token, and the alternative — picking a mask by rule
   * of thumb — is how a symbol ends up with a false finder in it.
   */
  let best = 0;
  let bestScore = Number.POSITIVE_INFINITY;
  for (let mask = 0; mask < 8; mask += 1) {
    applyMask(symbol, mask);
    drawFormatInfo(symbol, mask);
    const score = penalty(symbol);
    if (score < bestScore) {
      bestScore = score;
      best = mask;
    }
    applyMask(symbol, mask);
  }
  applyMask(symbol, best);
  drawFormatInfo(symbol, best);

  return { size: symbol.size, version, modules: symbol.modules };
}
