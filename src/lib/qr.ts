/**
 * A drawn symbol, mid-construction.
 *
 * `reserved` marks every module the function patterns own — finders, timing,
 * alignment, the format and version areas. Two jobs: the data walk steps over
 * them, and the mask is applied to everything they do not cover, which is the
 * spec's rule and the reason it cannot simply XOR the whole grid.
 */
interface Grid {
  size: number;
  modules: boolean[][];
  reserved: boolean[][];
}

function blank(version: number): Grid {
  const size = version * 4 + 17;
  return {
    size,
    modules: Array.from({ length: size }, () => new Array<boolean>(size).fill(false)),
    reserved: Array.from({ length: size }, () => new Array<boolean>(size).fill(false)),
  };
}

function setFunction(symbol: Grid, row: number, col: number, dark: boolean): void {
  symbol.modules[row]![col] = dark;
  symbol.reserved[row]![col] = true;
}

/** The three 7×7 corners, with the light separator that has to surround them. */
function drawFinder(symbol: Grid, row: number, col: number): void {
  for (let dy = -1; dy <= 7; dy += 1) {
    for (let dx = -1; dx <= 7; dx += 1) {
      const y = row + dy;
      const x = col + dx;
      if (y < 0 || y >= symbol.size || x < 0 || x >= symbol.size) continue;
      const ring = Math.max(Math.abs(dy - 3), Math.abs(dx - 3));
      // Rings 0-2 are the solid centre and its light gap; 3 is the black
      // border; 4 is the separator, which is the whole reason this loop runs
      // one module wider than the pattern it draws.
      setFunction(symbol, y, x, ring !== 2 && ring !== 4);
    }
  }
}

function drawFunctionPatterns(symbol: Grid, version: number): void {
  drawFinder(symbol, 0, 0);
  drawFinder(symbol, 0, symbol.size - 7);
  drawFinder(symbol, symbol.size - 7, 0);

  // The two timing lines: alternating modules along row and column 6, which is
  // what a scanner counts to work out how wide one module is.
  for (let i = 8; i < symbol.size - 8; i += 1) {
    setFunction(symbol, 6, i, i % 2 === 0);
    setFunction(symbol, i, 6, i % 2 === 0);
  }

  const centres = ALIGNMENT_CENTRES[version]!;
  for (const row of centres) {
    for (const col of centres) {
      // The three corners belong to the finders; an alignment pattern there
      // would overwrite them.
      const corner =
        (row === 6 && col === 6) ||
        (row === 6 && col === symbol.size - 7) ||
        (row === symbol.size - 7 && col === 6);
      if (corner) continue;
      for (let dy = -2; dy <= 2; dy += 1) {
        for (let dx = -2; dx <= 2; dx += 1) {
          const ring = Math.max(Math.abs(dy), Math.abs(dx));
          setFunction(symbol, row + dy, col + dx, ring !== 1);
        }
      }
    }
  }

  // The module that is always dark, and the format areas around it. The format
  // bits themselves are written once a mask has been chosen; reserving them
  // now is what keeps the data walk out of them.
  setFunction(symbol, symbol.size - 8, 8, true);
  for (let i = 0; i < 9; i += 1) {
    if (!symbol.reserved[8]![i]) setFunction(symbol, 8, i, false);
    if (!symbol.reserved[i]![8]) setFunction(symbol, i, 8, false);
  }
  for (let i = 0; i < 8; i += 1) {
    if (!symbol.reserved[8]![symbol.size - 1 - i]) setFunction(symbol, 8, symbol.size - 1 - i, false);
    if (!symbol.reserved[symbol.size - 1 - i]![8]) setFunction(symbol, symbol.size - 1 - i, 8, false);
  }

  if (version >= 7) drawVersionInfo(symbol, version);
}

/**
 * The version number, twice, for symbols big enough to be ambiguous.
 *
 * Six bits and a twelve-bit BCH check, in two 3×6 blocks by the top-right and
 * bottom-left finders. Only from version 7, because below that a scanner can
 * count modules and be sure.
 */
function drawVersionInfo(symbol: Grid, version: number): void {
  let remainder = version;
  for (let i = 0; i < 12; i += 1) {
    remainder = (remainder << 1) ^ ((remainder >>> 11) * 0x1f25);
  }
  const bits = ((version << 12) | remainder) >>> 0;

  for (let i = 0; i < 18; i += 1) {
    const dark = ((bits >>> i) & 1) === 1;
    const near = symbol.size - 11 + (i % 3);
    const far = Math.floor(i / 3);
    setFunction(symbol, far, near, dark);
    setFunction(symbol, near, far, dark);
  }
}

/**
 * The error-correction level and the mask, twice over, with a BCH check.
 *
 * Duplicated on purpose by the spec: the format is the one thing a scanner
 * cannot read the symbol without, so it is written beside two different
 * finders and either copy will do.
 */
function drawFormatInfo(symbol: Grid, mask: number): void {
  const data = (EC_LEVEL_M << 3) | mask;
  let remainder = data;
  for (let i = 0; i < 10; i += 1) {
    remainder = (remainder << 1) ^ ((remainder >>> 9) * 0x537);
  }
  const bits = (((data << 10) | remainder) ^ 0x5412) >>> 0;
  const bit = (index: number) => ((bits >>> index) & 1) === 1;

  // The copy that runs down the left column and along the top row, around the
  // top-left finder…
  for (let i = 0; i <= 5; i += 1) setFunction(symbol, i, 8, bit(i));
  setFunction(symbol, 7, 8, bit(6));
  setFunction(symbol, 8, 8, bit(7));
  setFunction(symbol, 8, 7, bit(8));
  for (let i = 9; i <= 14; i += 1) setFunction(symbol, 8, 14 - i, bit(i));

  // …and the copy split between the other two, which is the one a scanner
  // falls back on when the top-left corner is the part under a thumb.
  for (let i = 0; i <= 7; i += 1) setFunction(symbol, 8, symbol.size - 1 - i, bit(i));
  for (let i = 8; i <= 14; i += 1) setFunction(symbol, symbol.size - 15 + i, 8, bit(i));
}

/**
 * The codewords, laid in the zigzag the spec describes.
 *
 * Two-module columns from the right edge leftwards, alternating up and down,
 * skipping column 6 — which is the vertical timing line and not a column of
 * data at all — and stepping over every reserved module on the way.
 */
function drawCodewords(symbol: Grid, codewords: Uint8Array): void {
  let bit = 0;
  for (let right = symbol.size - 1; right >= 1; right -= 2) {
    if (right === 6) right = 5;
    for (let vertical = 0; vertical < symbol.size; vertical += 1) {
      for (let column = 0; column < 2; column += 1) {
        const x = right - column;
        const upward = ((right + 1) & 2) === 0;
        const y = upward ? symbol.size - 1 - vertical : vertical;
        if (symbol.reserved[y]![x] || bit >= codewords.length * 8) continue;
        symbol.modules[y]![x] = ((codewords[bit >>> 3]! >>> (7 - (bit & 7))) & 1) === 1;
        bit += 1;
      }
    }
  }
}

/** The eight masks, as the spec's conditions. A true condition flips the module. */
const MASKS: readonly ((row: number, col: number) => boolean)[] = [
  (row, col) => (row + col) % 2 === 0,
  (row) => row % 2 === 0,
  (_row, col) => col % 3 === 0,
  (row, col) => (row + col) % 3 === 0,
  (row, col) => (Math.floor(row / 2) + Math.floor(col / 3)) % 2 === 0,
  (row, col) => ((row * col) % 2) + ((row * col) % 3) === 0,
  (row, col) => (((row * col) % 2) + ((row * col) % 3)) % 2 === 0,
  (row, col) => (((row + col) % 2) + ((row * col) % 3)) % 2 === 0,
];

/** XOR in place. Called twice per candidate — once to try it, once to undo it. */
function applyMask(symbol: Grid, mask: number): void {
  const condition = MASKS[mask]!;
  for (let row = 0; row < symbol.size; row += 1) {
    for (let col = 0; col < symbol.size; col += 1) {
      if (!symbol.reserved[row]![col] && condition(row, col)) {
        symbol.modules[row]![col] = !symbol.modules[row]![col];
      }
    }
  }
}

/*
 * The four penalty rules, and why a symbol is scored at all.
 *
 * A mask exists to stop the data drawing something that looks like a function
 * pattern or a large blank field, and the scoring is how the encoder picks the
 * least misleading of the eight. The weights are the spec's: runs of five cost
 * 3 and a point per extra module, every 2×2 block of one colour costs 3, a
 * finder-shaped run costs 40, and a symbol wildly off half-dark costs 10 per
 * 5% of imbalance.
 *
 * Encoders famously disagree here, and this one will not always pick the mask
 * another tool picks for the same payload: the spec leaves open whether the
 * format modules are on the grid while it is scored, and whether the quiet
 * zone counts as the light space a finder-shaped run needs beside it. Both
 * answers produce a symbol that scans — the mask is written into the format
 * information, so a scanner is told which one it is looking at — so nothing
 * downstream depends on the choice, and the tests do not pin it.
 */
const PENALTY_RUN = 3;
const PENALTY_BLOCK = 3;
const PENALTY_FINDER = 40;
const PENALTY_BALANCE = 10;

/**
 * How many finder-like 1:1:3:1:1 runs the last seven runs contain.
 *
 * Read from a rolling history rather than by matching an eleven-module string,
 * because the pattern the spec penalises is a *proportion* — dark:light:dark
 * in 1:1:3:1:1 — with four modules of light space on one side, and a run
 * history is the only form in which both directions are cheap to test.
 */
function finderPatterns(history: readonly number[]): number {
  const unit = history[1]!;
  const core =
    unit > 0 &&
    history[2] === unit &&
    history[3] === unit * 3 &&
    history[4] === unit &&
    history[5] === unit;
  if (!core) return 0;
  return (
    (history[0]! >= unit * 4 && history[6]! >= unit ? 1 : 0) +
    (history[6]! >= unit * 4 && history[0]! >= unit ? 1 : 0)
  );
}

/**
 * Pushes a finished run onto the history.
 *
 * The very first run of a line is lengthened by a whole symbol width, because
 * what sits before it is the quiet zone — unbounded light space — and a finder
 * pattern that starts at the left edge has to be able to score.
 */
function pushRun(history: number[], run: number, size: number): void {
  history.pop();
  history.unshift(history[0] === 0 ? run + size : run);
}

function penalty(symbol: Grid): number {
  const { size, modules } = symbol;
  let score = 0;

  const scoreLine = (at: (index: number) => boolean) => {
    const history = [0, 0, 0, 0, 0, 0, 0];
    let colour = false;
    let run = 0;
    for (let i = 0; i < size; i += 1) {
      if (at(i) === colour) {
        run += 1;
        if (run === 5) score += PENALTY_RUN;
        else if (run > 5) score += 1;
      } else {
        pushRun(history, run, size);
        if (!colour) score += finderPatterns(history) * PENALTY_FINDER;
        colour = at(i);
        run = 1;
      }
    }
    // Closing the line: the run in hand is finished, and the quiet zone past
    // the right edge is added to it if it is a light one — the mirror of the
    // border `pushRun` adds at the start.
    if (colour) {
      pushRun(history, run, size);
      run = 0;
    }
    pushRun(history, run + size, size);
    score += finderPatterns(history) * PENALTY_FINDER;
  };

  for (let row = 0; row < size; row += 1) scoreLine((col) => modules[row]![col]!);
  for (let col = 0; col < size; col += 1) scoreLine((row) => modules[row]![col]!);

  for (let row = 0; row < size - 1; row += 1) {
    for (let col = 0; col < size - 1; col += 1) {
      const value = modules[row]![col];
      if (
        value === modules[row]![col + 1] &&
        value === modules[row + 1]![col] &&
        value === modules[row + 1]![col + 1]
      ) {
        score += PENALTY_BLOCK;
      }
    }
  }

  let dark = 0;
  for (const row of modules) for (const module of row) if (module) dark += 1;
  const total = size * size;
  const off = Math.ceil(Math.abs(dark * 20 - total * 10) / total) - 1;
  return score + off * PENALTY_BALANCE;
}

